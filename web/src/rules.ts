/**
 * rules.ts — TypeScript mirror of the ReconDesk Python engine
 * (src/recondesk/breaks.py).
 *
 * Every rule is an exact comparison across the three systems — billing
 * (payments ledger), crm (order book), warehouse (items + delivery dates)
 * — with disclosed weights and no LLM calls. Dates are ISO YYYY-MM-DD
 * strings, so ordering is lexicographic and day differences use UTC
 * parsing to avoid timezone drift.
 *
 * Score: sum of break bases (+ B1 delta / B4 days / B5 days extras)
 *        + age (0-10) + value (0/5/10), capped at 100.
 * Route: score >= 75 -> ESCALATE; B2/B3 holding >= R$500 -> ESCALATE;
 *        score >= 40 -> REVIEW; otherwise MONITOR.
 * data/test-vectors.json (generated by the Python pipeline) keeps both
 * implementations in exact agreement.
 */
import type { Break, BreakCode, CorrectionDraft, FlatOrder, Route } from "./types";

export const CLOSE_DATE = "2018-01-05";
export const CENT = 0.01;
export const ESCALATE_SCORE = 75;
export const REVIEW_SCORE = 40;
export const ESCALATE_MONEY = 500;

export const BASE_SCORE: Record<BreakCode, number> = {
  B1: 10, B2: 45, B3: 40, B4: 8, B5: 5, B6: 45, B7: 30, B8: 25,
};

export const PRIORITY: BreakCode[] = ["B2", "B3", "B6", "B7", "B1", "B4", "B5", "B8"];

export const BREAK_NAMES: Record<BreakCode, string> = {
  B1: "Amount mismatch",
  B2: "Canceled but paid",
  B3: "Paid but never shipped",
  B4: "Late delivery",
  B5: "Shipped after the limit date",
  B6: "Delivered but unpaid",
  B7: "Duplicate payment",
  B8: "Orphan record",
};

export function round2(x: number): number {
  return Math.round(x * 100) / 100;
}

function parseDay(s: string | null | undefined): number | null {
  if (!s) return null;
  const [y, m, d] = s.slice(0, 10).split("-").map(Number);
  if (!y || !m || !d) return null;
  return Date.UTC(y, m - 1, d);
}

function daysBetween(a: string | null | undefined, b: string | null | undefined): number | null {
  const da = parseDay(a);
  const db = parseDay(b);
  if (da === null || db === null) return null;
  return Math.round((db - da) / 86400000);
}

export function totals(order: FlatOrder): { paid: number; itemsPrice: number; freight: number; invoiced: number; delta: number } {
  const paid = round2(order.payments.reduce((s, p) => s + p.value, 0));
  const itemsPrice = round2(order.items.reduce((s, i) => s + i.price, 0));
  const freight = round2(order.items.reduce((s, i) => s + i.freight, 0));
  const invoiced = round2(itemsPrice + freight);
  return { paid, itemsPrice, freight, invoiced, delta: round2(paid - invoiced) };
}

export function brl(n: number): string {
  const sign = n < 0 ? "-" : "";
  return `${sign}R$ ${Math.abs(n).toFixed(2)}`;
}

/** Mirror of Python breaks.detect_breaks. */
export function detectBreaks(order: FlatOrder): Break[] {
  const t = totals(order);
  const status = order.status;
  const breaks: Break[] = [];

  if (order.items.length > 0 && t.paid > 0 && status !== "canceled" && Math.abs(t.delta) >= CENT) {
    breaks.push({
      code: "B1",
      delta: t.delta,
      detail: `Billing R$ ${t.paid.toFixed(2)} vs warehouse R$ ${t.invoiced.toFixed(2)} (delta R$ ${t.delta >= 0 ? "+" : "-"}${Math.abs(t.delta).toFixed(2)}).`,
    });
  }
  if (status === "canceled" && t.paid > 0) {
    breaks.push({
      code: "B2",
      refund_owed: t.paid,
      detail: `Order canceled; ${brl(t.paid)} captured and not refunded.`,
    });
  }
  if (status !== "canceled" && t.paid > 0 && order.items.length === 0) {
    breaks.push({
      code: "B3",
      amount_at_risk: t.paid,
      detail: `${brl(t.paid)} captured; warehouse holds no items for this order.`,
    });
  }
  if (status === "delivered" && order.delivered_customer_date && order.estimated_delivery_date) {
    const days = daysBetween(order.estimated_delivery_date, order.delivered_customer_date);
    if (days !== null && days > 0) {
      breaks.push({
        code: "B4",
        days_late: days,
        detail: `Delivered ${days} day(s) after the estimated date (${order.estimated_delivery_date} -> ${order.delivered_customer_date}).`,
      });
    }
  }
  let worstOver = 0;
  for (const item of order.items) {
    if (order.delivered_carrier_date && item.shipping_limit_date) {
      const over = daysBetween(item.shipping_limit_date, order.delivered_carrier_date);
      if (over !== null && over > worstOver) worstOver = over;
    }
  }
  if (worstOver > 0) {
    breaks.push({
      code: "B5",
      days_over: worstOver,
      detail: `Handed to the carrier ${worstOver} day(s) after the seller shipping-limit date.`,
    });
  }
  if (status === "delivered" && t.paid === 0) {
    breaks.push({
      code: "B6",
      amount_at_risk: t.invoiced,
      detail: `Delivered with no payment; warehouse invoice ${brl(t.invoiced)}.`,
    });
  }
  const seqs = order.payments.map((p) => p.sequential);
  if (new Set(seqs).size !== seqs.length) {
    breaks.push({ code: "B7", detail: "A payment sequence number repeats on this order." });
  }
  if (order.orphan) {
    breaks.push({ code: "B8", detail: "This record references an order_id found in no other system." });
  }
  return breaks;
}

function agePoints(order: FlatOrder): number {
  if (!order.purchase_date) return 0;
  const days = daysBetween(order.purchase_date, CLOSE_DATE);
  if (days === null) return 0;
  return Math.min(10, Math.floor(Math.max(0, days) / 30));
}

function valuePoints(order: FlatOrder): number {
  const paid = totals(order).paid;
  if (paid >= 2000) return 10;
  if (paid >= 500) return 5;
  return 0;
}

/** Mirror of Python breaks.score_order. */
export function scoreOrder(
  order: FlatOrder,
  breaks: Break[],
): { score: number; parts: { code: string; base: number; extra: number; subtotal: number }[] } {
  const parts: { code: string; base: number; extra: number; subtotal: number }[] = [];
  let total = 0;
  for (const b of breaks) {
    const base = BASE_SCORE[b.code];
    let extra = 0;
    if (b.code === "B1" && b.delta !== undefined) {
      extra = Math.min(25, Math.trunc(Math.abs(b.delta) * 2)) + (Math.abs(b.delta) >= 10 ? 5 : 0);
    } else if (b.code === "B4" && b.days_late !== undefined) {
      extra = Math.min(12, b.days_late);
    } else if (b.code === "B5" && b.days_over !== undefined) {
      extra = Math.min(10, b.days_over);
    }
    parts.push({ code: b.code, base, extra, subtotal: base + extra });
    total += base + extra;
  }
  const age = agePoints(order);
  const value = valuePoints(order);
  if (age) parts.push({ code: "AGE", base: age, extra: 0, subtotal: age });
  if (value) parts.push({ code: "VALUE", base: value, extra: 0, subtotal: value });
  total += age + value;
  return { score: Math.min(100, total), parts };
}

/** Mirror of Python breaks.money_at_stake. */
export function moneyAtStake(order: FlatOrder, breaks: Break[]): number {
  const t = totals(order);
  const codes = new Set(breaks.map((b) => b.code));
  if (codes.has("B2")) return t.paid;
  if (codes.has("B3")) return t.paid;
  if (codes.has("B6")) return t.invoiced;
  if (codes.has("B1")) return Math.abs(t.delta);
  return 0;
}

/** Mirror of Python breaks.route_order. */
export function routeOrder(order: FlatOrder, breaks: Break[], score: number): Route {
  const codes = new Set(breaks.map((b) => b.code));
  if (score >= ESCALATE_SCORE) return "ESCALATE";
  if ((codes.has("B2") || codes.has("B3")) && moneyAtStake(order, breaks) >= ESCALATE_MONEY) {
    return "ESCALATE";
  }
  if (score >= REVIEW_SCORE) return "REVIEW";
  return "MONITOR";
}

/** Mirror of Python breaks.recommended_action. Returns [action, instruction]. */
export function recommendedAction(order: FlatOrder, breaks: Break[]): [string, string] {
  const codes = new Set(breaks.map((b) => b.code));
  const t = totals(order);
  for (const code of PRIORITY) {
    if (!codes.has(code)) continue;
    const b = breaks.find((x) => x.code === code)!;
    if (code === "B2") {
      return ["ISSUE_REFUND", `Refund ${brl(t.paid)} to the customer; the order was canceled after capture.`];
    }
    if (code === "B3") {
      return ["CHASE_WAREHOUSE", `Confirm with the warehouse whether ${brl(t.paid)} of goods shipped; hold any further capture.`];
    }
    if (code === "B6") {
      return ["COLLECT_OR_WRITE_OFF", `Collect ${brl(t.invoiced)} from the customer, or write it off with approval.`];
    }
    if (code === "B7") {
      return ["REVERSE_DUPLICATE", "Reverse the duplicated payment sequence before the next settlement run."];
    }
    if (code === "B1") {
      return ["POST_CORRECTION", `Post the correcting journal below for the R$ ${b.delta !== undefined && b.delta >= 0 ? "+" : "-"}${Math.abs(b.delta ?? 0).toFixed(2)} difference; do not re-bill the customer.`];
    }
    if (code === "B4") {
      return ["LOG_SLA_BREACH", `Log the ${b.days_late}-day late delivery; claim the freight credit from the carrier if the contract allows.`];
    }
    if (code === "B5") {
      return ["LOG_SLA_BREACH", `Log the ${b.days_over}-day ship-limit breach with the seller; no money moves on this break alone.`];
    }
    if (code === "B8") {
      return ["TRACE_ORPHAN", "Trace the orphan record to its source system and re-key it to a real order."];
    }
  }
  return ["NO_ACTION", "The three systems agree; file the order with the close."];
}

/** Mirror of Python breaks.correction_draft. */
export function correctionDraft(order: FlatOrder, breaks: Break[]): CorrectionDraft[] {
  const drafts: CorrectionDraft[] = [];
  const t = totals(order);
  for (const b of breaks) {
    if (b.code === "B1" && b.delta !== undefined && Math.abs(b.delta) >= CENT) {
      const d = b.delta;
      if (d > 0) {
        drafts.push({
          code: "B1", kind: "journal", title: "Correcting journal — over-collection",
          lines: [`Dr Cash / clearing ${brl(d)}`, `Cr Customer refunds payable ${brl(d)}`],
          note: "Customer paid more than the warehouse invoiced. Hold the excess as a refund payable; do not recognize it as revenue.",
        });
      } else {
        drafts.push({
          code: "B1", kind: "journal", title: "Correcting journal — under-collection",
          lines: [`Dr Accounts receivable ${brl(Math.abs(d))}`, `Cr Sales revenue ${brl(Math.abs(d))}`],
          note: "Customer paid less than the warehouse invoiced. Recognize the receivable; chase only if the amount clears the R$10 materiality bar.",
        });
      }
    } else if (b.code === "B2") {
      drafts.push({
        code: "B2", kind: "journal", title: "Refund journal — canceled order",
        lines: [`Dr Refunds payable ${brl(t.paid)}`, `Cr Cash ${brl(t.paid)}`],
        note: "Refund the captured payment in full; attach the cancellation record from the order book.",
      });
    } else if (b.code === "B3") {
      drafts.push({
        code: "B3", kind: "chase", title: "Warehouse chase note",
        lines: [
          `Order ${order.order_id.slice(0, 8)}…: ${brl(t.paid)} captured, zero items in the warehouse system.`,
          "Ask: confirm shipment or confirm the order never left the warehouse.",
          "If nothing shipped, refund and cancel; if it shipped, re-key the items.",
        ],
        note: "Do not refund until the warehouse confirms nothing shipped.",
      });
    } else if (b.code === "B4") {
      drafts.push({
        code: "B4", kind: "sla_note", title: "Late-delivery SLA note",
        lines: [
          `Delivered ${b.days_late} day(s) late against the promised date.`,
          "File with the carrier claim if the freight contract carries a late-delivery credit.",
        ],
        note: "No ledger entry; this break is service, not money.",
      });
    } else if (b.code === "B5") {
      drafts.push({
        code: "B5", kind: "sla_note", title: "Ship-limit breach note",
        lines: [
          `Parcel reached the carrier ${b.days_over} day(s) after the seller shipping-limit date.`,
          "Raise with the seller; repeated breaches go on the seller scorecard.",
        ],
        note: "No ledger entry; this break is service, not money.",
      });
    } else if (b.code === "B6") {
      drafts.push({
        code: "B6", kind: "journal", title: "Unpaid delivery — collection or write-off",
        lines: [`Dr Accounts receivable ${brl(t.invoiced)}`, `Cr Sales revenue ${brl(t.invoiced)}`],
        note: "Goods delivered, no payment. Collect, or write off with approval — do not silently absorb it.",
      });
    } else if (b.code === "B7") {
      drafts.push({
        code: "B7", kind: "journal", title: "Duplicate payment reversal",
        lines: ["Dr Customer refunds payable (duplicated sequence amount)", "Cr Cash (duplicated sequence amount)"],
        note: "Reverse the duplicated sequence at its exact value before the next settlement run.",
      });
    }
  }
  return drafts;
}
